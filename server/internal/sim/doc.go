// Package sim は、ゲーム内時間で進む離散イベントシミュレーションの土台を提供する
// （DesignDoc §4、ADR-0004）。
//
// このタスク（T-102）で置く部品は次の 3 つ。
//
//   - SimTime: ゲーム内時間（ミリ秒）。0 は航行開始（§3.1）
//   - Scheduler: イベントを (At, Class, Seq) の昇順に取り出す優先度キュー（§4.2）
//   - Sub: ラウンドのシードと用途の名前から、用途ごとに独立した乱数列を作る（§9.1）
//
// # 決定性の規則（§9.2）
//
// 同じ入力（ステージ定義・シード・コマンドの列）からは、必ず同じ結果にならなければならない（V-6）。
// そのため、このパッケージとその下のパッケージ（テストを含む）では次を使わない。
//
//   - 実時間（現在時刻の取得や経過時間の計測）。時刻は SimTime だけで表す
//   - ゴルーチン・チャネル・チャネルの多重待ち
//   - 連想配列（map）の走査順に依存する処理。走査するときはキーを整列してから
//   - パッケージ全体で共有される math/rand の関数。乱数は Sub で作った列だけを使う
//   - 浮動小数点数の計算をスコアや判定に使うこと。スコアは整数で計算する
//
// CI では forbidigo で検出する（T-005）。
