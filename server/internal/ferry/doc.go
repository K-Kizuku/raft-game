// Package ferry は、Raft のノードの間のネットワークを置き換える Ferry Transport
// （DesignDoc §6）を、決定的なロジックとして実装する。
//
// Raft が出力したメッセージ（手紙）は、送信元の島の港に置かれる。港では規則
// R1〜R6 で手紙を合流・破棄し、手紙の数を抑える（V-7）。破棄はネットワークでの
// 欠落と同じ扱いで、手紙（*raftpb.Message）の中身は決して書き換えない。
// このパッケージは受け取ったポインタを持つだけで、複製もフィールドへの書き込みもしない。
//
// 中継倉庫（積み替え、FR-FERRY-06・ADR-0006）: 停泊中の船から、送信元がその島でない手紙
// （経由の手紙）を Unload で降ろすと、その島の中継倉庫に預ける。倉庫の手紙は RelayLoad で、
// その島に停泊中のどの船にも積み直せる。倉庫の手紙はどのノードにも渡さず、港キューにも入れない
// （Raft では処理しない。R5 の portCap にも数えない）。宛先の島に船で運ばれ、到着したときだけ
// 配達する。島ごとの倉庫の手紙は relayCap 通までで、超えるなら 1 通も降ろさない（ErrRelayFull）。
// 倉庫では規則 R1〜R6 を当てはめず、合流・破棄をしない。
//
// 状態の分け方（DTN-00 #363）: 各島の港と中継倉庫（手紙の中身・規則 R1〜R6）は Port、航路・船・積み荷と
// すべての手紙の所在の写しは Fleet が持つ。Transport は Fleet と島ごとの Port をつないだ単一プロセス用の型で、
// 手紙の ID を全体で 1 本の連番で振る。参照モデル（sim.Engine）は、島ごとの Port を islandcore に、Fleet を
// coordcore に持たせて、Transport と同じ順に呼ぶ。
//
// 時刻はすべて int64 のゲーム内時間（ミリ秒、0 = 航行開始）で受ける。値は
// sim.SimTime と同じだが、依存の向き（sim → ferry）を守るため sim を import しない。
// 船の到着の時刻は Depart が返し、スケジューラへの登録は呼び出し側（sim.Engine）が行う。
//
// 終わった手紙の片付け: 配達済み・破棄した手紙は Fleet.Reclaim を呼ぶまで写しに残り、
// Letter で引ける。呼び出し側は、配達・破棄の結果からドメインイベントを作り終えたあとに
// Reclaim を呼ぶ。呼べば、持つ手紙の数は港・船の上限（V-7）で抑えられる。呼ばなければ
// 終わった手紙を持ち続け、メモリは増え続ける。Reclaim の時点は操作の結果（ID・破棄・
// 配達・エラー）に影響せず、手紙の ID は再利用しない。
//
// 決定性: time・goroutine・チャネル・乱数・浮動小数点を使わず、map は検索だけに
// 使って走査しない。同じ操作の列からは、必ず同じ ID・同じ破棄・同じ配達になる。
//
// Transport・Fleet・Port は 1 つの goroutine から使う（ロックを持たない）。
