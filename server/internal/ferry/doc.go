// Package ferry は、Raft のノードの間のネットワークを置き換える Ferry Transport
// （DesignDoc §6）を、決定的なロジックとして実装する。
//
// Raft が出力したメッセージ（手紙）は、送信元の島の港に置かれる。港では規則
// R1〜R6 で手紙を合流・破棄し、手紙の数を抑える（V-7）。破棄はネットワークでの
// 欠落と同じ扱いで、手紙（*raftpb.Message）の中身は決して書き換えない。
// このパッケージは受け取ったポインタを持つだけで、複製もフィールドへの書き込みもしない。
//
// 時刻はすべて int64 のゲーム内時間（ミリ秒、0 = 航行開始）で受ける。値は
// sim.SimTime と同じだが、依存の向き（sim → ferry）を守るため sim を import しない。
// 船の到着の時刻は Depart が返し、スケジューラへの登録は呼び出し側（sim.Engine）が行う。
//
// 決定性: time・goroutine・チャネル・乱数・浮動小数点を使わず、map は検索だけに
// 使って走査しない。同じ操作の列からは、必ず同じ ID・同じ破棄・同じ配達になる。
//
// Transport は 1 つの goroutine から使う（ロックを持たない）。
